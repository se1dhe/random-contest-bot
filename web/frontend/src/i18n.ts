export function normalizeLanguage(language?: string | null): ContestLanguage {
    return language === 'uk' || language === 'en' ? language : 'ru';
}

export function t(language: ContestLanguage | string | undefined | null, key: string, values?: Record<string, string>): string {
    const lang = normalizeLanguage(language);
    let value = messages[lang][key] || messages.ru[key] || key;
    if (values) {
        Object.entries(values).forEach(([name, replacement]) => {
            value = value.replace(`{${name}}`, replacement);
        });
    }
    return value;
}
